import Foundation

enum AppThemeBuiltIn: String, CaseIterable, Identifiable, Sendable {
    case ghostty
    case kitty
    case herdr
    case neovim

    var id: String {
        rawValue
    }

    var name: String {
        switch self {
        case .ghostty: "Ghostty"
        case .kitty: "kitty"
        case .herdr: "herdr"
        case .neovim: "Neovim"
        }
    }

    static let ghosttyThemeLine = "theme = light:omniwm-light,dark:omniwm-dark"

    func outputs(configHome: URL) -> [AppThemeOutput] {
        func path(_ relative: String) -> String {
            configHome.appendingPathComponent(relative).path
        }
        return switch self {
        case .ghostty:
            [
                AppThemeOutput(
                    path: path("ghostty/themes/omniwm-light"),
                    template: .text(Self.ghosttyTemplate),
                    variant: .light
                ),
                AppThemeOutput(
                    path: path("ghostty/themes/omniwm-dark"),
                    template: .text(Self.ghosttyTemplate),
                    variant: .dark
                )
            ]
        case .kitty:
            [
                AppThemeOutput(
                    path: path("kitty/light-theme.auto.conf"),
                    template: .text(Self.kittyTemplate),
                    variant: .light
                ),
                AppThemeOutput(
                    path: path("kitty/dark-theme.auto.conf"),
                    template: .text(Self.kittyTemplate),
                    variant: .dark
                )
            ]
        case .herdr:
            [AppThemeOutput(
                path: path("herdr/config.toml"),
                template: .text(Self.herdrTemplate),
                table: ["theme", "custom"]
            )]
        case .neovim:
            [
                AppThemeOutput(path: path("nvim/lua/omniwm.lua"), template: .text(Self.neovimTemplate), variant: .dark),
                AppThemeOutput(
                    path: path("nvim/colors/omniwm.lua"),
                    template: .text(Self.neovimColorscheme),
                    variant: .dark
                )
            ]
        }
    }

    func reload(savedMachines: Bool) -> AppThemeReloadAction? {
        switch self {
        case .ghostty: .ghostty
        case .kitty: .kitty
        case .herdr: .herdr(savedMachines: savedMachines)
        case .neovim: .neovim
        }
    }

    var template: String {
        switch self {
        case .ghostty: Self.ghosttyTemplate
        case .kitty: Self.kittyTemplate
        case .herdr: Self.herdrTemplate
        case .neovim: Self.neovimTemplate
        }
    }

    static let ghosttyTemplate = """
    # Generated by OmniWM from its {{mode}} palette. OmniWM rewrites this file when the palette changes.
    background = {{colors.background.default.hex}}
    foreground = {{colors.foreground.default.hex}}
    cursor-color = {{colors.accent.default.hex}}
    cursor-text = {{colors.accentForeground.default.hex}}
    selection-background = {{colors.accentContainer.default.hex}}
    selection-foreground = {{colors.accentContainerForeground.default.hex}}
    \((0 ..< AppThemeANSI.colorCount).map { "palette = \($0)={{colors.ansi\($0).default.hex}}" }.joined(separator: "\n"))

    """

    static let kittyTemplate = """
    # Generated by OmniWM from its {{mode}} palette. OmniWM rewrites this file when the palette changes.
    foreground {{colors.foreground.default.hex}}
    background {{colors.background.default.hex}}
    selection_foreground {{colors.accentContainerForeground.default.hex}}
    selection_background {{colors.accentContainer.default.hex}}
    cursor {{colors.accent.default.hex}}
    cursor_text_color {{colors.accentForeground.default.hex}}
    url_color {{colors.accent.default.hex}}
    active_border_color {{colors.accent.default.hex}}
    inactive_border_color {{colors.border.default.hex}}
    active_tab_foreground {{colors.accentForeground.default.hex}}
    active_tab_background {{colors.accent.default.hex}}
    inactive_tab_foreground {{colors.secondaryForeground.default.hex}}
    inactive_tab_background {{colors.surface.default.hex}}
    tab_bar_background {{colors.background.default.hex}}
    mark1_foreground {{colors.accentForeground.default.hex}}
    mark1_background {{colors.accent.default.hex}}
    \((0 ..< AppThemeANSI.colorCount).map { "color\($0) {{colors.ansi\($0).default.hex}}" }.joined(separator: "\n"))

    """

    static let herdrTemplate = """
    [theme.custom]
    # Generated by OmniWM from its {{mode}} palette. OmniWM rewrites this table when the palette changes.
    accent = "{{colors.accent.default.hex}}"
    panel_bg = "reset"
    surface0 = "reset"
    surface1 = "reset"
    surface_dim = "reset"
    active_row_bg = "{{colors.accentContainer.default.hex}}"
    selection_bg = "{{colors.accentContainer.default.hex}}"
    overlay0 = "{{colors.mutedForeground.default.hex}}"
    overlay1 = "{{colors.secondaryForeground.default.hex}}"
    text = "{{colors.foreground.default.hex}}"
    subtext0 = "{{colors.secondaryForeground.default.hex}}"
    red = "{{colors.ansi1.default.hex}}"
    green = "{{colors.ansi2.default.hex}}"
    yellow = "{{colors.ansi3.default.hex}}"
    peach = "{{colors.ansi11.default.hex}}"
    blue = "{{colors.ansi4.default.hex}}"
    mauve = "{{colors.ansi5.default.hex}}"
    teal = "{{colors.ansi6.default.hex}}"

    """
}
